"""scripts/update_prices.py: LiteLLM's price file to openvigie's bundled table (FR-4, D4)."""

import importlib.util
import json
import sys
import tomllib
from datetime import UTC, datetime
from decimal import Decimal
from pathlib import Path
from types import ModuleType
from typing import Any

import pytest

from openvigie.model import UsageQuality, UsageRecord
from openvigie.pricing import compute_cost, load_price_table

ROOT = Path(__file__).parents[1]
EXCERPT = ROOT / "tests" / "fixtures" / "litellm" / "model_prices_excerpt.json"
REV = "a" * 40
REV2 = "b" * 40
HAND = """[providers.anthropic]
cached_input_included = false

[providers.openai]
cached_input_included = true

[[models]]
provider = "anthropic"
id = "claude-sonnet-4-6"
aliases = ["claude-sonnet-4-5"]
input = 3.0
output = 15.0
as_of = "2026-10-14"

[[models]]
provider = "openai"
id = "gpt-5"
input = 1.25
output = 10.0
unverified = true

# --- BEGIN GENERATED by scripts/update_prices.py: do not edit by hand ---
# --- END GENERATED ---
"""


def _load() -> ModuleType:
    path = ROOT / "scripts" / "update_prices.py"
    spec = importlib.util.spec_from_file_location("update_prices", path)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules["update_prices"] = module
    spec.loader.exec_module(module)
    return module


up = _load()


def excerpt() -> dict[str, Any]:
    data: dict[str, Any] = json.loads(EXCERPT.read_text())
    return data


@pytest.fixture
def generated() -> tuple[str, str]:
    text: str
    summary: str
    text, summary = up.update(HAND, excerpt(), REV)
    return text, summary


def models(text: str) -> dict[str, dict[str, Any]]:
    return {m["id"]: m for m in tomllib.loads(text)["models"]}


def table(tmp_path: Path, text: str) -> Any:
    path = tmp_path / "prices.toml"
    path.write_text(text)
    return load_price_table(path)


def test_maps_per_token_fields_to_per_million(generated: tuple[str, str]) -> None:
    opus = models(generated[0])["claude-opus-4-1"]
    assert opus == {
        "provider": "anthropic", "id": "claude-opus-4-1", "aliases": ["anthropic/claude-opus-4-1"],
        "input": 15.0, "output": 75.0, "cache_read": 1.5, "cache_write_5m": 18.75,
        "cache_write_1h": 30.0, "source": f"litellm@{REV}", "unverified": True,
    }  # fmt: skip


def test_float_noise_is_rounded_away(generated: tuple[str, str]) -> None:
    assert "cache_read = 0.3\n" in generated[0]
    assert models(generated[0])["claude-3-5-haiku-20241022"]["cache_read"] == 0.08


def test_long_context_tier_falls_back_to_base_rates(generated: tuple[str, str]) -> None:
    nova = models(generated[0])["gpt-6.2-nova"]
    assert nova["above"] == {"prompt_tokens": 272000, "input": 4.0, "output": 15.0,
                             "cache_read": 0.4}  # fmt: skip
    sonnet = models(generated[0])["claude-sonnet-3-9"]["above"]
    # no long-context cache read price: the base one applies
    assert sonnet == {"prompt_tokens": 200000, "input": 6.0, "output": 22.5, "cache_read": 0.3,
                      "cache_write_5m": 7.5, "cache_write_1h": 12.0}  # fmt: skip


def test_generated_table_prices_records(generated: tuple[str, str], tmp_path: Path) -> None:
    prices = table(tmp_path, generated[0])
    now = datetime(2026, 10, 16, tzinfo=UTC)
    record = UsageRecord("r", "a", now, provider="openai", response_model="gpt-6.2-nova",
                         input_tokens=300_000, cache_read_input_tokens=100_000,
                         output_tokens=1_000, quality=UsageQuality.EXACT)  # fmt: skip
    cost = compute_cost(record, prices)
    assert cost.amount == (200_000 * Decimal(4) + 100_000 * Decimal("0.4") + 1_000 * 15) / 10**6
    one_hour = UsageRecord("r", "a", now, provider="anthropic", response_model="claude-opus-4-1",
                           input_tokens=0, output_tokens=0, cache_creation_input_tokens=3_000_000,
                           cache_creation_1h_input_tokens=1_000_000,
                           quality=UsageQuality.EXACT)  # fmt: skip
    assert compute_cost(one_hour, prices).amount == Decimal("67.5")  # 2M x 18.75 + 1M x 30
    assert prices.find("openai", "openai/gpt-5-mini") is prices.find("openai", "gpt-5-mini")


def test_provider_prefixed_names(generated: tuple[str, str]) -> None:
    entries = models(generated[0])
    assert entries["gpt-5-mini"]["aliases"] == ["openai/gpt-5-mini"]
    assert "openai/gpt-4.1" in entries["gpt-4.1"]["aliases"]  # only listed with its prefix
    # priced differently from the bare name: kept as its own entry, not folded
    assert "aliases" not in entries["gpt-4o"] and entries["openai/gpt-4o"]["input"] == 5.0


def test_skips_other_providers_modes_and_bad_entries(generated: tuple[str, str]) -> None:
    entries = models(generated[0])
    assert "gpt-5-codex-mini" in entries  # Responses-only models are billed like chat ones
    for skipped in ("sample_spec", "azure/gpt-5", "bedrock/us.anthropic.claude-opus-4-1-v1:0",
                    "gpt-image-1", "text-embedding-3-small", "gpt-realtime", "gpt-broken",
                    'gpt-"quoted"'):  # fmt: skip
        assert skipped not in entries
    assert "3 other provider" in generated[1] and "2 not a chat model" in generated[1]
    assert "2 missing or invalid per-token price" in generated[1]
    assert "1 unusual model name" in generated[1]


def test_hand_entries_win_and_stay_untouched(generated: tuple[str, str]) -> None:
    text, summary = generated
    head = HAND[: HAND.index(up.BEGIN)]
    assert text.startswith(head)
    ids = [m["id"] for m in tomllib.loads(text)["models"]]
    assert ids.count("gpt-5") == 1 and "claude-sonnet-4-5" not in ids
    assert "- `gpt-5` (openai)" in summary  # unverified hand entry LiteLLM also prices
    assert "2 hand entry wins" in summary


def test_several_long_context_tiers_keep_the_first(generated: tuple[str, str]) -> None:
    assert models(generated[0])["gpt-tiered"]["above"]["prompt_tokens"] == 128000
    assert "gpt-tiered: long-context tiers at [128000, 256000] tokens, kept 128000" in generated[1]


def test_rerun_and_newer_revision_with_same_prices_give_no_diff(generated: tuple[str, str]) -> None:
    text = generated[0]
    assert up.update(text, excerpt(), REV)[0] == text
    again, summary = up.update(text, excerpt(), REV2)
    assert again == text
    assert "No price changes." in summary


def test_price_change_updates_only_that_entry(generated: tuple[str, str]) -> None:
    data = excerpt()
    data["gpt-5-mini"]["output_cost_per_token"] = 3e-06
    data["openai/gpt-5-mini"]["output_cost_per_token"] = 3e-06
    data["gpt-4.5-preview"] = {"input_cost_per_token": 7.5e-05, "output_cost_per_token": 1.5e-04,
                               "litellm_provider": "openai", "mode": "chat"}  # fmt: skip
    del data["claude-3-5-haiku-20241022"]
    text, summary = up.update(generated[0], data, REV2)
    entries = models(text)
    assert entries["gpt-5-mini"]["output"] == 3.0
    assert entries["gpt-5-mini"]["source"] == f"litellm@{REV2}"
    assert entries["claude-opus-4-1"]["source"] == f"litellm@{REV}"
    assert f"at commit {REV2}" in text
    assert summary.count("**changed**") == 1
    assert (
        "- **changed** `gpt-5-mini` (openai): input 0.25, output 2.0, cache_read 0.025 (also "
        "openai/gpt-5-mini) → input 0.25, output 3.0, cache_read 0.025 (also " in summary
    )
    assert "- **added** `gpt-4.5-preview` (openai): input 75.0, output 150.0" in summary
    assert "- **removed** `claude-3-5-haiku-20241022` (anthropic), was input 0.8" in summary


def test_bundled_table_has_the_generated_block() -> None:
    head, block, _ = up.split((ROOT / "src" / "openvigie" / "prices.toml").read_text())
    assert all("source" not in m for m in tomllib.loads(head)["models"])
    if block.strip():
        assert "Copyright (c) 2023 Berri AI" in block  # LiteLLM's MIT notice travels with it


@pytest.mark.parametrize("revision", ["main", "a" * 39, "A" * 40])
def test_only_pinned_revisions(revision: str) -> None:
    with pytest.raises(SystemExit):
        up.update(HAND, excerpt(), revision)
    with pytest.raises(SystemExit):
        up.main(["--revision", revision, "--input", str(EXCERPT)])


def test_markers_are_required() -> None:
    with pytest.raises(SystemExit, match="markers"):
        up.update(HAND.replace(up.END, ""), excerpt(), REV)


def test_main_writes_table_and_summary(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    prices = tmp_path / "prices.toml"
    prices.write_text(HAND)
    summary = tmp_path / "summary.md"
    argv = ["--revision", REV, "--input", str(EXCERPT), "--prices", str(prices)]
    assert up.main([*argv, "--summary", str(summary)]) == 0
    assert "claude-opus-4-1" in prices.read_text()
    assert summary.read_text() == capsys.readouterr().out
    assert "**added** `claude-opus-4-1` (anthropic)" in summary.read_text()
    before = prices.stat().st_mtime_ns
    assert up.main(argv) == 0
    assert prices.stat().st_mtime_ns == before  # nothing changed, nothing written
