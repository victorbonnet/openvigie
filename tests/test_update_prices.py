import pytest

from openvigie.model import UsageQuality, UsageRecord
from openvigie.pricing import compute_cost, load_price_table

ROOT = Path(__file__).parents[1]
FIXTURES = ROOT / "tests" / "fixtures" / "litellm"
# entries copied unchanged from LiteLLM's model_prices_and_context_window.json at RECORDED
EXCERPT = FIXTURES / "model_prices_excerpt.json"
RECORDED = "e45f2737d33772efd72df232cdc7a6e56154dfd7"
EDGES = FIXTURES / "edge_cases.json"  # made up, in LiteLLM's format
BUNDLED = ROOT / "src" / "openvigie" / "prices.toml"
REV = "a" * 40
REV2 = "b" * 40
HAND = """[providers.anthropic]
cached_input_included = false

[providers.openai]
cached_input_included = true

[[models]]
provider = "anthropic"
id = "claude-sonnet-4-6"
aliases = ["claude-sonnet-4-5"]
input = 3.0
output = 15.0
as_of = "2026-10-14"

# --- BEGIN GENERATED by scripts/update_prices.py: do not edit by hand ---
# --- END GENERATED ---
"""


def _load() -> ModuleType:
    path = ROOT / "scripts" / "update_prices.py"
    spec = importlib.util.spec_from_file_location("update_prices", path)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules["update_prices"] = module
    spec.loader.exec_module(module)
    return module


up = _load()


def excerpt(path: Path = EDGES) -> dict[str, Any]:
    data: dict[str, Any] = json.loads(path.read_text())
    return data


@pytest.fixture
def generated() -> tuple[str, str]:
    """The made-up edge cases against a small hand section."""
    text: str
    summary: str
    text, summary = up.update(HAND, excerpt(), REV)
    return text, summary


@pytest.fixture
def recorded() -> tuple[str, str]:
    """The recorded excerpt against the real bundled hand section."""
    text: str
    summary: str
    text, summary = up.update(BUNDLED.read_text(), excerpt(EXCERPT), RECORDED)
    return text, summary


def models(text: str) -> dict[str, dict[str, Any]]:
    return {m["id"]: m for m in tomllib.loads(text)["models"]}


def table(tmp_path: Path, text: str) -> Any:
    path = tmp_path / "prices.toml"
    path.write_text(text)
    return load_price_table(path)


# --- recorded LiteLLM data against the real bundled table ------------------------------------


def test_recorded_mapping(recorded: tuple[str, str]) -> None:
    entries = models(recorded[0])
    assert entries["claude-mythos-preview"] == {
        "provider": "anthropic", "id": "claude-mythos-preview", "input": 10.0, "output": 50.0,
        "cache_read": 1.0, "cache_write_5m": 12.5, "cache_write_1h": 20.0,
        "source": f"litellm@{RECORDED}", "unverified": True,
    }  # fmt: skip
    # batch, flex and priority variants are ignored
    assert entries["gpt-5.4"]["above"] == {"prompt_tokens": 272000, "input": 5.0,
                                           "output": 22.5, "cache_read": 0.5}  # fmt: skip
    assert entries["gpt-5.4-pro"]["above"]["output"] == 270.0  # mode "responses"
    generated = {name for name, entry in entries.items() if entry.get("source")}
    assert generated == {"claude-mythos-preview", "gpt-5-mini", "gpt-5.4", "gpt-5.4-2026-03-05",
                         "gpt-5.4-pro"}  # fmt: skip
    assert ("Skipped: 6 hand entry wins, 1 missing or invalid per-token price, "
            "1 not a chat model, 3 other provider.") in recorded[1]  # fmt: skip


@pytest.mark.parametrize("model", ["claude-haiku-5-5", "gpt-6.1-sol"])
def test_recorded_mapping_matches_hand_verified_entry(model: str) -> None:
    """LiteLLM's rates, converted, equal the ones checked against the provider's page (LiteLLM
    may know more: it has a cache write rate for gpt-6.1-sol, which the hand entry leaves out)."""
    prices, warning = up.convert_one(excerpt(EXCERPT)[model])
    hand = models(BUNDLED.read_text())[model]
    rates, above = dict(prices.rates), dict(prices.above)
    assert warning is None
    assert {k: rates[k] for k in up.RATE_FIELDS if k in hand} == {
        k: Decimal(str(hand[k])) for k in up.RATE_FIELDS if k in hand
    }
    assert prices.above_tokens == hand["above"]["prompt_tokens"]
    assert {k: above[k] for k in hand["above"] if k != "prompt_tokens"} == {
        k: Decimal(str(v)) for k, v in hand["above"].items() if k != "prompt_tokens"
    }


def test_hand_entries_win_for_dated_ids(recorded: tuple[str, str], tmp_path: Path) -> None:
    text, summary = recorded
    assert text.startswith(BUNDLED.read_text().split(up.BEGIN)[0])  # hand section untouched
    entries = models(text)
    assert "claude-sonnet-4-5-20250929" not in entries and "gpt-5-2025-08-07" not in entries
    prices = table(tmp_path, text)
    sonnet = prices.find("anthropic", "claude-sonnet-4-5-20250929")
    assert sonnet.model_id == "claude-sonnet-4-6" and not sonnet.unverified
    gpt5 = prices.find("openai", "gpt-5-2025-08-07")
    assert gpt5.model_id == "gpt-5" and gpt5.source is None
    assert "- `gpt-5` (openai)" in summary  # unverified hand entry LiteLLM also prices


def test_bundled_table_has_the_generated_block() -> None:
    head, block, _ = up.split(BUNDLED.read_text())
    assert all("source" not in m for m in tomllib.loads(head)["models"])
    if block.strip():
        assert "Copyright (c) 2023 Berri AI" in block  # LiteLLM's MIT notice travels with it


