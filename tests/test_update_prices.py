def test_long_context_tier_falls_back_to_base_rates(generated: tuple[str, str]) -> None:
    nova = models(generated[0])["gpt-6.2-nova"]
    assert nova["above"] == {"prompt_tokens": 272000, "input": 4.0, "output": 15.0,
                             "cache_read": 0.4}  # fmt: skip
    sonnet = models(generated[0])["claude-sonnet-3-9"]["above"]
    # no long-context cache read price: the base one applies
    assert sonnet == {"prompt_tokens": 200000, "input": 6.0, "output": 22.5, "cache_read": 0.3,
                      "cache_write_5m": 7.5, "cache_write_1h": 12.0}  # fmt: skip


def test_generated_table_prices_records(generated: tuple[str, str], tmp_path: Path) -> None:
    prices = table(tmp_path, generated[0])
    now = datetime(2026, 10, 16, tzinfo=UTC)
    record = UsageRecord("r", "a", now, provider="openai", response_model="gpt-6.2-nova",
                         input_tokens=300_000, cache_read_input_tokens=100_000,
                         output_tokens=1_000, quality=UsageQuality.EXACT)  # fmt: skip
    cost = compute_cost(record, prices)
    assert cost.amount == (200_000 * Decimal(4) + 100_000 * Decimal("0.4") + 1_000 * 15) / 10**6
    one_hour = UsageRecord("r", "a", now, provider="anthropic", response_model="claude-opus-4-1",
                           input_tokens=0, output_tokens=0, cache_creation_input_tokens=3_000_000,
                           cache_creation_1h_input_tokens=1_000_000,
                           quality=UsageQuality.EXACT)  # fmt: skip
    assert compute_cost(one_hour, prices).amount == Decimal("67.5")  # 2M x 18.75 + 1M x 30


