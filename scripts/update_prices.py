#!/usr/bin/env python3
"""Regenerate the LiteLLM part of the bundled price table (FR-4, D4). Dev tool, not shipped.

uv run scripts/update_prices.py --revision <40-hex LiteLLM commit> [--input FILE]
    [--prices src/openvigie/prices.toml] [--summary FILE]

Reads LiteLLM's ``model_prices_and_context_window.json`` at a pinned commit (from ``--input``
or raw.githubusercontent.com) and rewrites only the block between the GENERATED markers of
``prices.toml``. Everything above the block is hand-maintained and wins: a LiteLLM model is left
out when its id, or its id without a date suffix, is a hand entry's id or alias. Generated
entries are ``unverified`` and carry ``source = "litellm@<commit>"``, the revision at which their
rates last changed, so a newer revision with the same rates gives no diff. The output depends
only on the input file, the revision and the hand section, so running it twice gives no diff.

openvigie never runs this at run time: the table ships with the package (no phone-home).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
import urllib.request
from collections.abc import Mapping
from dataclasses import dataclass, replace
from decimal import Decimal
from pathlib import Path
from typing import Annotated, Any

from pydantic import ConfigDict, Field, Strict, TypeAdapter, ValidationError
from pydantic.dataclasses import dataclass as pydantic_dataclass

from openvigie.pricing import DATE_SUFFIX, PriceFile

ROOT = Path(__file__).resolve().parents[1]
PRICES = ROOT / "src" / "openvigie" / "prices.toml"
URL = "https://raw.githubusercontent.com/BerriAI/litellm/{rev}/model_prices_and_context_window.json"
MAX_BYTES = 32 * 1024 * 1024  # the file is ~3 MB; a bigger one is a mistake, not data
PROVIDERS = ("anthropic", "openai")
# "responses" is how LiteLLM lists Responses-API-only models (the Codex family); same billing
MODES = ("chat", "responses")
BEGIN = "# --- BEGIN GENERATED by scripts/update_prices.py: do not edit by hand ---"
END = "# --- END GENERATED ---"
REVISION = re.compile(r"^[0-9a-f]{40}$")
# model names end up in TOML and HTML: keep to what real model ids use
NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._:/@+-]{0,127}$")
ABOVE = re.compile(r"^(?P<field>[a-z0-9_]+?)_above_(?P<k>\d{1,5})k_tokens$")
MILLION = Decimal(1_000_000)
STEP = Decimal("0.000001")  # per million tokens; drops float noise like 3.0000000000000004

# LiteLLM per-token field -> openvigie per-million field
FIELDS = {
    "input_cost_per_token": "input",
    "output_cost_per_token": "output",
    "cache_read_input_token_cost": "cache_read",
    "cache_creation_input_token_cost": "cache_write_5m",
    "cache_creation_input_token_cost_above_1hr": "cache_write_1h",
}
RATE_FIELDS = ("input", "output", "cache_read", "cache_write_5m", "cache_write_1h")

PerToken = Annotated[float, Strict(), Field(ge=0, le=1, allow_inf_nan=False)]
PER_TOKEN: TypeAdapter[float] = TypeAdapter(PerToken, config=ConfigDict(hide_input_in_errors=True))


# LiteLLM entries have dozens of fields we don't use, so this one boundary ignores extras;
# what we read is still strictly typed and bounded.
@pydantic_dataclass(frozen=True, config=ConfigDict(extra="ignore", hide_input_in_errors=True))
class LiteLLMEntry:
    litellm_provider: Annotated[str, Strict(), Field(max_length=64)]
    mode: Annotated[str, Strict(), Field(max_length=64)]
    input_cost_per_token: PerToken
    output_cost_per_token: PerToken


ENTRY: TypeAdapter[LiteLLMEntry] = TypeAdapter(LiteLLMEntry)


Rates = tuple[tuple[str, Decimal], ...]  # (field, USD per million tokens), in RATE_FIELDS order


@dataclass(frozen=True)
class Prices:
    rates: Rates
    above_tokens: int | None = None  # long-context tier: prompts above this many tokens
    above: Rates = ()


@dataclass(frozen=True)
class Entry:
    """One generated ``[[models]]`` entry."""

    provider: str
    id: str
    prices: Prices
    source: str = ""

    def same_as(self, other: Entry) -> bool:
        """Equal in everything a reviewer cares about, i.e. all but the source revision."""
        return self.prices == other.prices


def per_million(value: float) -> Decimal:
    return (Decimal(repr(value)) * MILLION).quantize(STEP).normalize()


def convert_one(raw: Mapping[str, Any]) -> tuple[Prices, str | None]:
    """Rates and long-context tier of one LiteLLM entry, plus a warning if any."""
    base = {
        ours: per_million(PER_TOKEN.validate_python(raw[theirs]))
        for theirs, ours in FIELDS.items()
        if raw.get(theirs) is not None
    }
    tiers: dict[int, dict[str, Decimal]] = {}
    for key, value in raw.items():
        match = ABOVE.match(key)
        if match and match["field"] in FIELDS and value is not None:
            tier = tiers.setdefault(int(match["k"]) * 1000, {})
            tier[FIELDS[match["field"]]] = per_million(PER_TOKEN.validate_python(value))
    rates = tuple((name, base[name]) for name in RATE_FIELDS if name in base)
    if not tiers:
        return Prices(rates), None
    # openvigie models a single long-context tier: keep the first one and say so
    threshold = min(tiers)
    warning = f"long-context tiers at {sorted(tiers)} tokens, kept {threshold}"
    # LiteLLM bills a field with no long-context price at its base rate; so do we
    above = {**base, **tiers[threshold]}
    long = tuple((name, above[name]) for name in RATE_FIELDS if name in above)
    return Prices(rates, threshold, long), warning if len(tiers) > 1 else None


@dataclass
class Result:
    entries: list[Entry]
    skipped: dict[str, int]  # reason -> count
    warnings: list[str]
    hand_covered: list[str]  # unverified hand entries LiteLLM also prices


def convert(data: Mapping[str, Any], hand: PriceFile) -> Result:
    """LiteLLM's table to generated entries, without source revisions yet."""
    skipped: dict[str, int] = {}
    warnings: list[str] = []
    taken = {(m.provider, name) for m in hand.models for name in (m.id, *m.aliases)}
    unverified = {(m.provider, name): m.id for m in hand.models if m.unverified
                  for name in (m.id, *m.aliases)}  # fmt: skip
    covered: set[str] = set()
    entries = []

    def skip(reason: str) -> None:
        skipped[reason] = skipped.get(reason, 0) + 1

    for key, raw in sorted(data.items()):
        if not isinstance(raw, dict) or raw.get("litellm_provider") not in PROVIDERS:
            skip("other provider")
            continue
        if raw.get("mode") not in MODES:
            skip("not a chat model")
            continue
        if not NAME.match(key):
            skip("unusual model name")
            continue
        try:
            entry = ENTRY.validate_python(raw)
            prices, warning = convert_one(raw)
        except (ValidationError, KeyError):
            skip("missing or invalid per-token price")
            continue
        provider = entry.litellm_provider
        # PriceTable.find tries the exact id before the undated one, so a generated
        # "claude-x-20250929" would shadow a hand-verified "claude-x"
        name = next((n for n in (key, DATE_SUFFIX.sub("", key)) if (provider, n) in taken), None)
        if name is not None:
            if (provider, name) in unverified:
                covered.add(f"`{unverified[(provider, name)]}` ({provider})")
            skip("hand entry wins")
            continue
        if warning:
            warnings.append(f"{key}: {warning}")
        entries.append(Entry(provider, key, prices))
    entries.sort(key=lambda e: (e.provider, e.id))
    return Result(entries, skipped, warnings, sorted(covered))


# --- prices.toml -----------------------------------------------------------------------------


def split(text: str) -> tuple[str, str, str]:
    """Hand section, generated block (markers excluded), and what follows it."""
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        raise SystemExit(f"prices.toml: missing {BEGIN!r} ... {END!r} markers")
    return text[:start], text[start + len(BEGIN) : end], text[end + len(END) :]


def _rates(values: Mapping[str, Any]) -> Rates:
    return tuple((name, Decimal(str(values[name]))) for name in RATE_FIELDS if name in values)


def parse_block(block: str) -> dict[tuple[str, str], Entry]:
    """The entries of the current generated block, keyed by (provider, id), in file order."""
    entries = {}
    for model in tomllib.loads(block).get("models", []):
        above = model.get("above")
        prices = (
            Prices(_rates(model), above["prompt_tokens"], _rates(above))
            if above
            else Prices(_rates(model))
        )
        entry = Entry(model["provider"], model["id"], prices, model.get("source", ""))
        entries[(entry.provider, entry.id)] = entry
    return entries


def number(value: Decimal) -> str:
    text = f"{value:f}"
    return text if "." in text else f"{text}.0"


def render_entry(entry: Entry) -> str:
    lines = ["[[models]]", f'provider = "{entry.provider}"', f'id = "{entry.id}"']
    lines += [f"{name} = {number(value)}" for name, value in entry.prices.rates]
    if entry.prices.above_tokens is not None:
        parts = [f"prompt_tokens = {entry.prices.above_tokens}"]
        parts += [f"{name} = {number(value)}" for name, value in entry.prices.above]
        lines.append("above = { " + ", ".join(parts) + " }")
    lines += [f'source = "{entry.source}"', "unverified = true"]
    return "\n".join(lines)


def render_block(entries: list[Entry], revision: str) -> str:
    header = f"""
# Rates from LiteLLM's model_prices_and_context_window.json at commit {revision}
# (https://github.com/BerriAI/litellm), converted to USD per million tokens. Each entry's
# `source` is the commit at which its rates last changed. Not checked against the providers'
# pages: to verify one, move it above this block without `unverified` and with `as_of`.
#
# LiteLLM data: Copyright (c) 2023 Berri AI. Permission is hereby granted, free of charge, to
# any person obtaining a copy of this software and associated documentation files (the
# "Software"), to deal in the Software without restriction, including without limitation the
# rights to use, copy, modify, merge, publish, distribute, sublicense, and/or sell copies of the
# Software, and to permit persons to whom the Software is furnished to do so, subject to the
# following conditions: The above copyright notice and this permission notice shall be included
# in all copies or substantial portions of the Software. THE SOFTWARE IS PROVIDED "AS IS",
# WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES
# OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL
# THE AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER LIABILITY, WHETHER
# IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM, OUT OF OR IN CONNECTION WITH THE
# SOFTWARE OR THE USE OR OTHER DEALINGS IN THE SOFTWARE.
"""
    return header + "".join(f"\n{render_entry(e)}\n" for e in entries) + "\n"


def update(text: str, data: Mapping[str, Any], revision: str) -> tuple[str, str]:
    """New prices.toml text and a Markdown summary of what changed."""
    if not REVISION.match(revision):
        raise SystemExit("--revision must be a full 40-character commit SHA")
    head, block, tail = split(text)
    hand = TypeAdapter(PriceFile).validate_python(tomllib.loads(head + tail))
    old = parse_block(block)
    result = convert(data, hand)
    new = []
    for entry in result.entries:
        before = old.get((entry.provider, entry.id))
        unchanged = before is not None and before.same_as(entry)
        new.append(replace(entry, source=before.source if before and unchanged else
                           f"litellm@{revision}"))  # fmt: skip
    changed = list(old) != [(e.provider, e.id) for e in new] or any(
        not entry.same_as(old[(entry.provider, entry.id)]) for entry in new
    )
    # same prices at a newer revision: leave the file alone, so the weekly job opens no PR
    if changed or not block.strip():
        block = render_block(new, revision)
    updated = f"{head}{BEGIN}{block}{END}{tail}"
    # never write a table openvigie would refuse to load
    TypeAdapter(PriceFile).validate_python(tomllib.loads(updated))
    return updated, summarize(old, {(e.provider, e.id): e for e in new}, result, revision)


def describe(entry: Entry) -> str:
    rates = ", ".join(f"{name} {number(value)}" for name, value in entry.prices.rates)
    if entry.prices.above_tokens is not None:
        tier = ", ".join(f"{name} {number(value)}" for name, value in entry.prices.above)
        rates += f"; above {entry.prices.above_tokens} prompt tokens: {tier}"
    return rates


def summarize(old: dict[tuple[str, str], Entry], new: dict[tuple[str, str], Entry],
              result: Result, revision: str) -> str:  # fmt: skip
    lines = [f"Bundled prices regenerated from LiteLLM commit `{revision}`.", ""]
    changes = []
    for key in sorted(old.keys() | new.keys()):
        name = f"`{key[1]}` ({key[0]})"
        if key not in new:
            changes.append(f"- **removed** {name}, was {describe(old[key])}")
        elif key not in old:
            changes.append(f"- **added** {name}: {describe(new[key])}")
        elif not old[key].same_as(new[key]):
            changes.append(f"- **changed** {name}: {describe(old[key])} → {describe(new[key])}")
    lines += changes or ["No price changes."]
    if result.hand_covered:
        lines += ["", "Unverified hand entries LiteLLM also prices (the hand entry still wins; "
                  "delete it to use LiteLLM's rates):", ""]  # fmt: skip
        lines += [f"- {name}" for name in result.hand_covered]
    if result.warnings:
        lines += ["", "Warnings:", ""] + [f"- {w}" for w in result.warnings]
    skipped = ", ".join(f"{n} {reason}" for reason, n in sorted(result.skipped.items()))
    lines += ["", f"{len(new)} generated entries. Skipped: {skipped or 'none'}."]
    return "\n".join(lines) + "\n"


def fetch(revision: str) -> bytes:
    with urllib.request.urlopen(URL.format(rev=revision), timeout=60) as response:  # noqa: S310
        body: bytes = response.read(MAX_BYTES + 1)
    return body


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--revision", required=True, help="LiteLLM commit SHA (40 hex chars)")
    parser.add_argument("--input", type=Path, help="local copy of the JSON file at that commit")
    parser.add_argument("--prices", type=Path, default=PRICES)
    parser.add_argument("--summary", type=Path, help="write a Markdown summary here")
    args = parser.parse_args(argv)
    if not REVISION.match(args.revision):
        parser.error("--revision must be a full 40-character commit SHA")
    raw = args.input.read_bytes() if args.input else fetch(args.revision)
    if len(raw) > MAX_BYTES:
        parser.error(f"LiteLLM file is over {MAX_BYTES} bytes")
    data = json.loads(raw)
    if not isinstance(data, dict):
        parser.error("LiteLLM file is not a JSON object")
    text, summary = update(args.prices.read_text(encoding="utf-8"), data, args.revision)
    if text != args.prices.read_text(encoding="utf-8"):
        args.prices.write_text(text, encoding="utf-8")
    if args.summary:
        args.summary.write_text(summary, encoding="utf-8")
    sys.stdout.write(summary)
    return 0


if __name__ == "__main__":
    sys.exit(main())
